"""Show-Cause Notice PDF for a flagged instrument (declared Column A vs bank-verified Column B)."""
import hashlib
import io
import json
from datetime import date
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from .models import Instrument

FIELDS = [("ref_no", "FDR / reference no."), ("bank", "Issuing bank"), ("amount", "Deposit amount (Rs.)"),
          ("issue_date", "Date of deposit"), ("maturity_date", "Maturity date"), ("lien", "Joint lien (AICTE)")]


def _fmt(k, v):
    if v is None:
        return "-"
    if k == "amount":
        return f"{float(v):,.2f}"
    if k == "lien":
        return "Marked" if v else "Not marked"
    return v.strftime("%d-%b-%Y") if hasattr(v, "strftime") else str(v)


def notice_content(inst: Instrument, today: date) -> dict:
    """Canonical facts the notice is built from; its SHA-256 is the notice's integrity hash."""
    return {
        "notice_no": f"SCN/{today.year}/{inst.id:05d}", "date": today.isoformat(),
        "institution": {"pid": inst.institution.pid, "name": inst.institution.name},
        "instrument": {"id": inst.id, "kind": inst.kind},
        "declared": {k: _fmt(k, getattr(inst, "d_" + k)) for k, _ in FIELDS},
        "bank_verified": {k: _fmt(k, getattr(inst, "b_" + k)) for k, _ in FIELDS},
        "mismatches": [m["field"] for m in (inst.mismatches or [])],
        "bank_channel": inst.bank_channel, "document_sha256": inst.doc_sha256,
    }


def content_hash(content: dict) -> str:
    return hashlib.sha256(json.dumps(content, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def build_pdf(inst: Instrument, today: date) -> tuple[bytes, str]:
    c = notice_content(inst, today)
    digest = content_hash(c)
    st = getSampleStyleSheet()
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=18 * mm, bottomMargin=22 * mm,
                            title=c["notice_no"], author="Data_VeriGuard")
    bad = set(c["mismatches"])
    rows = [["Field", "Column A: Institution-declared", "Column B: Bank-verified", ""]]
    style = [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0b2a4a")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
             ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#b9c4d3")), ("FONTSIZE", (0, 0), (-1, -1), 9),
             ("VALIGN", (0, 0), (-1, -1), "MIDDLE")]
    for i, (k, label) in enumerate(FIELDS, start=1):
        flag = k in bad or ("bank_record" in bad and c["bank_verified"][k] == "-")
        rows.append([label, c["declared"][k], c["bank_verified"][k], "MISMATCH" if flag else "OK"])
        if flag:
            style.append(("BACKGROUND", (0, i), (-1, i), colors.HexColor("#fde8e8")))
    t = Table(rows, colWidths=[42 * mm, 52 * mm, 52 * mm, 24 * mm])
    t.setStyle(TableStyle(style))
    body = [
        Paragraph("All India Council for Technical Education (AICTE) - Regulation Bureau", st["Heading3"]),
        Paragraph("SHOW-CAUSE NOTICE: SECURITY DEPOSIT / FDR DISCREPANCY", st["Title"]),
        Paragraph(f"Notice no.: <b>{c['notice_no']}</b> &nbsp;&nbsp; Date: {today:%d-%b-%Y}", st["Normal"]),
        Paragraph(f"To: The Head of Institution, <b>{c['institution']['name']}</b> (PID {c['institution']['pid']})", st["Normal"]),
        Paragraph(f"Instrument: {c['instrument']['kind']} {c['declared']['ref_no']} &nbsp;|&nbsp; Verification channel: {c['bank_channel'] or '-'}", st["Normal"]),
        Spacer(1, 6 * mm),
        Paragraph("The details declared by your institution do not match the independent bank-verified record for the "
                  "instrument below. You are called upon to show cause, within 15 days of this notice, why the deposit should not be "
                  "treated as unverified under the AICTE Approval Process Handbook, together with supporting bank confirmation.", st["Normal"]),
        Spacer(1, 5 * mm), t, Spacer(1, 6 * mm),
        Paragraph(f"Mismatched fields: <b>{', '.join(sorted(bad)) or 'none'}</b>", st["Normal"]),
        Spacer(1, 4 * mm),
        Paragraph(f"Integrity hash (SHA-256 of the notice particulars): <font size=7>{digest}</font>", st["Normal"]),
        Paragraph(f"Source document SHA-256: <font size=7>{c['document_sha256'] or '-'}</font>", st["Normal"]),
    ]

    def footer(canvas, _doc):
        canvas.setFont("Helvetica", 8)
        canvas.drawString(20 * mm, 12 * mm, "Generated by NidhiSetu | Data_VeriGuard | Team ID 152167 | SIH26265 | Prototype on synthetic data")

    doc.build(body, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue(), digest
