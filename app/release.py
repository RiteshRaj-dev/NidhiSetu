"""APH Clause 6.46 release workflow: document checklist + PGRC / Vigilance / Grants clearances,
then Competent Authority decision. Generates an NOC (FDR/RPGF) or Sanction Order (RTGS)."""
import hashlib
from datetime import date
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas
from sqlalchemy.orm import Session
from . import audit
from .config import VAULT_DIR
from .models import Instrument, ReleaseRequest, User
from .rules import get_rules
from .services import validity


def evaluate(db: Session, inst: Instrument, req: ReleaseRequest, today: date) -> dict:
    rules = get_rules(db)
    have = {d.doc_type for d in inst.documents}
    docs = {k: k in have for k in rules["release_documents"]}
    clr = {k: req.clearances.get(k) for k in rules["release_clearances"]}
    blockers = []
    if validity(inst, today, rules) != "MATURED":
        blockers.append("Instrument has not matured yet")
    if inst.verification != "VERIFIED":
        blockers.append("Instrument is not bank-verified (" + inst.verification + ")")
    blockers += [f"Missing document: {k}" for k, ok in docs.items() if not ok]
    blockers += [f"Clearance pending/denied: {k.upper()}" for k, ok in clr.items() if ok is not True]
    return {"documents": docs, "clearances": clr, "eligible": not blockers, "blockers": blockers}


def open_request(db: Session, user: User, inst: Instrument) -> ReleaseRequest:
    req = ReleaseRequest(instrument_id=inst.id, checklist={}, clearances={})
    db.add(req)
    inst.state = "RELEASE_PENDING"
    db.flush()
    audit.append(db, user.username, user.role, "release.open", "instrument", inst.id, {"request_id": req.id})
    db.commit()
    return req


def set_clearance(db: Session, user: User, req: ReleaseRequest, cell: str, approve: bool) -> ReleaseRequest:
    c = dict(req.clearances or {})
    c[cell] = approve
    req.clearances = c
    audit.append(db, user.username, user.role, f"release.clearance.{cell}", "instrument", req.instrument_id, {"approved": approve})
    db.commit()
    return req


def decide(db: Session, user: User, inst: Instrument, req: ReleaseRequest, approve: bool, today: date) -> ReleaseRequest:
    rules = get_rules(db)
    ev = evaluate(db, inst, req, today)
    if approve and not ev["eligible"]:
        raise ValueError("; ".join(ev["blockers"]))
    req.state = "APPROVED" if approve else "REJECTED"
    if approve:
        otype = rules["order_type"].get(inst.kind, "NOC")
        req.order_type = otype
        req.order_ref = f"{'NOC' if otype == 'NOC' else 'SO'}/{today.year}/{req.id:05d}"
        inst.state = "RELEASED"
        _write_order(inst, req, today)
    else:
        inst.state = "ACTIVE"
    audit.append(db, user.username, user.role, "release.decision", "instrument", inst.id,
                 {"approved": approve, "order_ref": req.order_ref})
    db.commit()
    return req


def _write_order(inst: Instrument, req: ReleaseRequest, today: date) -> None:
    path = VAULT_DIR / f"order_{req.id}.pdf"
    c = canvas.Canvas(str(path), pagesize=A4)
    c.setFont("Helvetica-Bold", 14)
    title = "NO OBJECTION CERTIFICATE" if req.order_type == "NOC" else "COUNCIL SANCTION ORDER"
    c.drawString(60, 780, "All India Council for Technical Education (AICTE) - Regulation Bureau")
    c.drawString(60, 755, title)
    c.setFont("Helvetica", 11)
    lines = [f"Order Ref: {req.order_ref}", f"Date: {today:%d-%b-%Y}", f"Institution: {inst.institution.name} ({inst.institution.pid})",
             f"Instrument: {inst.kind} {inst.d_ref_no}", f"Bank: {inst.d_bank}", f"Amount: Rs. {float(inst.d_amount):,.2f}",
             f"Maturity: {inst.d_maturity_date:%d-%b-%Y}", "Release approved by Competent Authority after PGRC, Vigilance and Grants clearances.",
             "(Prototype output on synthetic data)"]
    for i, ln in enumerate(lines):
        c.drawString(60, 720 - 22 * i, ln)
    c.setFont("Helvetica", 8)
    c.drawString(60, 40, "Generated by NidhiSetu | Data_VeriGuard | Team ID 152167 | SIH26265")
    c.save()
    audit_hash = hashlib.sha256(path.read_bytes()).hexdigest()
    c2 = path.with_suffix(".sha256"); c2.write_text(audit_hash)
